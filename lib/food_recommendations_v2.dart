  // ฟังก์ชันดึงคำแนะนำจากอาหารและโรค
  static FoodRecommendation? getRecommendation(
      String foodName, String disease) {
    final foodDb = database[foodName];
    if (foodDb == null) return null;
    return foodDb[disease];
  }

  // ฟังก์ชันดึงคำแนะนำเฉพาะโรคที่ผู้ใช้มี
  static List<FoodRecommendation> getRecommendationsForDiseases(
      String foodName, List<String>? userDiseases) {
    if (userDiseases == null || userDiseases.isEmpty) return [];

    final foodDb = database[foodName];
    if (foodDb == null) return [];

    return userDiseases
        .map((disease) => foodDb[disease])
        .whereType<FoodRecommendation>()
        .toList();
  }
